CREATE TABLE IF NOT EXISTS upload_task (
 md5 CHAR(32) PRIMARY KEY, file_name VARCHAR(255) NOT NULL, file_size BIGINT NOT NULL,
 total_chunks INT NOT NULL, object_key VARCHAR(512) NOT NULL, upload_id VARCHAR(512) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS uploaded_file (
 md5 CHAR(32) PRIMARY KEY, file_name VARCHAR(255) NOT NULL, file_size BIGINT NOT NULL,
 object_key VARCHAR(512) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
